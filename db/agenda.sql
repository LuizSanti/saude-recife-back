CREATE EXTENSION IF NOT EXISTS btree_gist;

-- 1. Grade semanal recorrente. Uma linha representa uma faixa/turno.
CREATE TABLE IF NOT EXISTS public.grade_atendimento (
    id_grade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_profissional BIGINT NOT NULL,
    id_clinica BIGINT NOT NULL,
    id_especialidade BIGINT NOT NULL,
    dia_semana SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7), -- 1=segunda ... 7=domingo
    hora_inicio TIME NOT NULL,
    hora_fim TIME NOT NULL,
    duracao_minutos INTEGER NOT NULL CHECK (duracao_minutos > 0),
    intervalo_minutos INTEGER NOT NULL DEFAULT 0 CHECK (intervalo_minutos >= 0),
    vigencia_inicio DATE NOT NULL,
    vigencia_fim DATE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_grade_horario CHECK (hora_fim > hora_inicio),
    CONSTRAINT ck_grade_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
    CONSTRAINT fk_grade_profissional_clinica
        FOREIGN KEY (id_profissional, id_clinica)
        REFERENCES public.profissional_clinica (id_profissional, id_clinica)
        ON DELETE RESTRICT,
    CONSTRAINT fk_grade_profissional_especialidade
        FOREIGN KEY (id_profissional, id_especialidade)
        REFERENCES public.profissional_especialidade (id_profissional, id_especialidade)
        ON DELETE RESTRICT,
    CONSTRAINT fk_grade_clinica_especialidade
        FOREIGN KEY (id_clinica, id_especialidade)
        REFERENCES public.clinica_especialidade (id_clinica, id_especialidade)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_grade_busca_disponibilidade
    ON public.grade_atendimento (id_clinica, id_especialidade, dia_semana, ativo, vigencia_inicio);

CREATE INDEX IF NOT EXISTS ix_grade_profissional
    ON public.grade_atendimento (id_profissional, dia_semana, ativo);

-- Evita que duas grades ativas do mesmo profissional se sobreponham no mesmo
-- dia e em datas de vigência coincidentes, inclusive entre clínicas distintas.
CREATE OR REPLACE FUNCTION public.fn_validar_sobreposicao_grade()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.ativo THEN
        IF EXISTS (
            SELECT 1
            FROM public.grade_atendimento g
            WHERE g.ativo
              AND g.id_profissional = NEW.id_profissional
              AND g.dia_semana = NEW.dia_semana
              AND g.id_grade <> COALESCE(NEW.id_grade, -1)
              AND NEW.hora_inicio < g.hora_fim
              AND g.hora_inicio < NEW.hora_fim
              AND daterange(
                    g.vigencia_inicio,
                    CASE WHEN g.vigencia_fim IS NULL THEN NULL ELSE g.vigencia_fim + 1 END,
                    '[)'
                  ) &&
                  daterange(
                    NEW.vigencia_inicio,
                    CASE WHEN NEW.vigencia_fim IS NULL THEN NULL ELSE NEW.vigencia_fim + 1 END,
                    '[)'
                  )
        ) THEN
            RAISE EXCEPTION 'A grade sobrepõe outro turno ativo deste profissional.'
                USING ERRCODE = '23P01';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_sobreposicao_grade ON public.grade_atendimento;
CREATE TRIGGER trg_validar_sobreposicao_grade
BEFORE INSERT OR UPDATE ON public.grade_atendimento
FOR EACH ROW EXECUTE FUNCTION public.fn_validar_sobreposicao_grade();

-- 2. Bloqueios individuais do profissional.
CREATE TABLE IF NOT EXISTS public.indisponibilidade_profissional (
    id_indisponibilidade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_profissional BIGINT NOT NULL REFERENCES public.profissional(id_profissional) ON DELETE RESTRICT,
    inicio TIMESTAMPTZ NOT NULL,
    fim TIMESTAMPTZ NOT NULL,
    motivo VARCHAR(250),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_indisponibilidade_periodo CHECK (fim > inicio)
);

CREATE INDEX IF NOT EXISTS ix_indisponibilidade_profissional_periodo
    ON public.indisponibilidade_profissional (id_profissional, inicio, fim)
    WHERE ativo = TRUE;

-- 3. Exceções pontuais:
-- BLOQUEIO: impede atendimento no período.
-- ALTERACAO_HORARIO: substitui a janela normal naquele período.
-- TURNO_EXTRA: acrescenta uma janela fora da grade recorrente.
-- O backend precisa aplicar a semântica do tipo ao calcular disponibilidade.
CREATE TABLE IF NOT EXISTS public.excecao_agenda (
    id_excecao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(30) NOT NULL
        CHECK (tipo IN ('BLOQUEIO', 'ALTERACAO_HORARIO', 'TURNO_EXTRA')),
    id_clinica BIGINT NOT NULL REFERENCES public.clinica(id_clinica) ON DELETE RESTRICT,
    id_profissional BIGINT REFERENCES public.profissional(id_profissional) ON DELETE RESTRICT,
    id_especialidade BIGINT REFERENCES public.especialidade(id_especialidade) ON DELETE RESTRICT,
    inicio TIMESTAMPTZ NOT NULL,
    fim TIMESTAMPTZ NOT NULL,
    motivo VARCHAR(250),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_excecao_periodo CHECK (fim > inicio),
    CONSTRAINT fk_excecao_profissional_clinica
        FOREIGN KEY (id_profissional, id_clinica)
        REFERENCES public.profissional_clinica (id_profissional, id_clinica)
        ON DELETE RESTRICT,
    CONSTRAINT fk_excecao_profissional_especialidade
        FOREIGN KEY (id_profissional, id_especialidade)
        REFERENCES public.profissional_especialidade (id_profissional, id_especialidade)
        ON DELETE RESTRICT,
    CONSTRAINT fk_excecao_clinica_especialidade
        FOREIGN KEY (id_clinica, id_especialidade)
        REFERENCES public.clinica_especialidade (id_clinica, id_especialidade)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_excecao_agenda_periodo
    ON public.excecao_agenda (id_clinica, inicio, fim)
    WHERE ativo = TRUE;

CREATE INDEX IF NOT EXISTS ix_excecao_profissional_periodo
    ON public.excecao_agenda (id_profissional, inicio, fim)
    WHERE ativo = TRUE AND id_profissional IS NOT NULL;

-- 4. Agendamentos. O código tem formato validado e unicidade entre agendamentos
-- confirmados (índice parcial). Ajuste a regra/formato se o enunciado RF11
-- definir um padrão diferente.
CREATE TABLE IF NOT EXISTS public.agendamento (
    id_agendamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES public.paciente(id_paciente) ON DELETE RESTRICT,
    id_profissional BIGINT NOT NULL,
    id_clinica BIGINT NOT NULL,
    id_especialidade BIGINT NOT NULL,
    id_grade BIGINT REFERENCES public.grade_atendimento(id_grade) ON DELETE SET NULL,
    inicio TIMESTAMPTZ NOT NULL,
    fim TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMADO'
        CHECK (status IN ('CONFIRMADO', 'CANCELADO')),
    codigo_confirmacao VARCHAR(12) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelado_em TIMESTAMPTZ,
    motivo_cancelamento VARCHAR(500),
    CONSTRAINT ck_agendamento_periodo CHECK (fim > inicio),
    CONSTRAINT ck_agendamento_codigo CHECK (codigo_confirmacao ~ '^[A-Z0-9]{6,12}$'),
    CONSTRAINT ck_agendamento_cancelamento CHECK (
        (status = 'CONFIRMADO' AND cancelado_em IS NULL)
        OR
        (status = 'CANCELADO' AND cancelado_em IS NOT NULL)
    ),
    CONSTRAINT fk_agendamento_profissional_clinica
        FOREIGN KEY (id_profissional, id_clinica)
        REFERENCES public.profissional_clinica (id_profissional, id_clinica)
        ON DELETE RESTRICT,
    CONSTRAINT fk_agendamento_profissional_especialidade
        FOREIGN KEY (id_profissional, id_especialidade)
        REFERENCES public.profissional_especialidade (id_profissional, id_especialidade)
        ON DELETE RESTRICT,
    CONSTRAINT fk_agendamento_clinica_especialidade
        FOREIGN KEY (id_clinica, id_especialidade)
        REFERENCES public.clinica_especialidade (id_clinica, id_especialidade)
        ON DELETE RESTRICT,
    CONSTRAINT ex_agendamento_profissional_periodo
        EXCLUDE USING gist (
            id_profissional WITH =,
            tstzrange(inicio, fim, '[)') WITH &&
        )
        WHERE (status = 'CONFIRMADO')
);

CREATE INDEX IF NOT EXISTS ix_agendamento_paciente_inicio
    ON public.agendamento (id_paciente, inicio DESC);

CREATE INDEX IF NOT EXISTS ix_agendamento_profissional_inicio
    ON public.agendamento (id_profissional, inicio)
    WHERE status = 'CONFIRMADO';

CREATE INDEX IF NOT EXISTS ix_agendamento_clinica_especialidade_inicio
    ON public.agendamento (id_clinica, id_especialidade, inicio)
    WHERE status = 'CONFIRMADO';

CREATE UNIQUE INDEX IF NOT EXISTS uq_agendamento_codigo_confirmado
    ON public.agendamento (codigo_confirmacao)
    WHERE status = 'CONFIRMADO';

-- 5. Configuração da antecedência máxima. A tabela fica sem valor inicial
-- porque o limite de dias ainda não foi definido pelo projeto.
CREATE TABLE IF NOT EXISTS public.configuracao_agendamento (
    id_configuracao SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id_configuracao = 1),
    antecedencia_maxima_dias INTEGER NOT NULL CHECK (antecedencia_maxima_dias > 0),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE public.grade_atendimento IS
    'Grade semanal recorrente; cada registro representa uma faixa de atendimento.';
COMMENT ON TABLE public.indisponibilidade_profissional IS
    'Bloqueios individuais que reduzem a disponibilidade do profissional.';
COMMENT ON TABLE public.excecao_agenda IS
    'Exceções pontuais de bloqueio, alteração de horário ou turno extra.';
COMMENT ON TABLE public.agendamento IS
    'Agendamentos confirmados ou cancelados; cancelamentos preservam o registro.';
COMMENT ON TABLE public.configuracao_agendamento IS
    'Parâmetros de negócio do agendamento, incluindo antecedência máxima configurável.';

COMMIT;
